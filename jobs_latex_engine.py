"""Deterministic Markdown-to-LaTeX export for Cerry Jobs. No raw model LaTeX is executed."""
import os
import re
import shutil
import subprocess
import tempfile
import time
import unicodedata
from pathlib import Path

ESCAPES = {
    '\\': r'\textbackslash{}', '&': r'\&', '%': r'\%', '$': r'\$',
    '#': r'\#', '_': r'\_', '{': r'\{', '}': r'\}',
    '~': r'\textasciitilde{}', '^': r'\textasciicircum{}',
}
UNICODE = {'–': '--', '—': '---', '“': '``', '”': "''", '‘': '`', '’': "'",
           '…': r'\ldots{}', '•': r'\textbullet{}', '→': r'\ensuremath{\rightarrow}',
           'α': r'\ensuremath{\alpha}', 'β': r'\ensuremath{\beta}',
           'γ': r'\ensuremath{\gamma}', 'Δ': r'\ensuremath{\Delta}',
           'μ': r'\ensuremath{\mu}', 'µ': r'\ensuremath{\mu}',
           '≤': r'\ensuremath{\leq}', '≥': r'\ensuremath{\geq}', '±': r'\ensuremath{\pm}'}


def escape(text):
    text = unicodedata.normalize('NFC', str(text))
    return ''.join(ESCAPES.get(c, UNICODE.get(c, c)) for c in text if c != '\x00')


def inline(text):
    # Strip Markdown hyperlinks to their label; never treat a destination as a TeX command.
    text = re.sub(r'\[([^\]]+)\]\([^)]+\)', r'\1', text)
    parts = re.split(r'(\*\*[^*]+\*\*|`[^`]+`)', text)
    out = []
    for part in parts:
        if part.startswith('**') and part.endswith('**'):
            out.append(r'\textbf{' + escape(part[2:-2]) + '}')
        elif part.startswith('`') and part.endswith('`'):
            out.append(r'\texttt{' + escape(part[1:-1]) + '}')
        else:
            out.append(escape(part))
    return ''.join(out)


def document(markdown, kind='cv'):
    lines = markdown.replace('\r\n', '\n').splitlines()
    body, listing, fenced = [], False, False
    def close_list():
        nonlocal listing
        if listing:
            body.append(r'\end{itemize}')
            listing = False
    for line in lines:
        text = line.strip()
        if text.startswith('```'):
            close_list()
            fenced = not fenced
            continue
        if fenced:
            body.append(r'\noindent\texttt{' + escape(line).replace(' ', r'\ ') + r'}\par')
        elif re.match(r'^[-*]\s+|^\d+[.)]\s+', text):
            if not listing:
                body.append(r'\begin{itemize}')
                listing = True
            body.append(r'\item ' + inline(re.sub(r'^([-*]|\d+[.)])\s+', '', text)))
        else:
            close_list()
            heading = re.match(r'^(#{1,6})\s+(.+)', text)
            if heading:
                level, title = len(heading[1]), inline(heading[2])
                if level == 1:
                    body.append(r'{\Large\bfseries ' + title + r'}\par\medskip')
                else:
                    body.append(r'\section*{' + title + '}')
            elif text:
                body.append(inline(text) + r'\par')
            else:
                body.append(r'\smallskip')
    close_list()
    preamble = r'''% Generated by Cerry. Open with TeXstudio and compile with pdfLaTeX.
% Text derives from the already-tailored and checked application documents.
\documentclass[11pt,a4paper]{article}
\usepackage[utf8]{inputenc}
\usepackage[T1]{fontenc}
\usepackage[margin=2cm]{geometry}
\usepackage{lmodern}
\setlength{\parindent}{0pt}
\setlength{\parskip}{0.3em}
\pagestyle{empty}
\begin{document}
'''
    return preamble + '\n'.join(body) + '\n' + r'\end{document}' + '\n'


def compile_pdf(tex_path, executable='', timeout=60, should_stop=lambda: False):
    """Compile our generated source in a temporary build directory. Never reuse a stale PDF."""
    tex_path = Path(tex_path).resolve()
    exe = executable.strip() or shutil.which('pdflatex')
    if not exe:
        return {'ok': False, 'message': 'pdflatex not found. Open the .tex file in TeXstudio, or set the executable path.'}
    dest = tex_path.parent / 'latex_pdf'
    dest.mkdir(exist_ok=True)
    log_path = dest / (tex_path.stem + '_compile.txt')
    with tempfile.TemporaryDirectory(prefix='cerry_tex_') as tmp:
        work = Path(tmp)
        shutil.copy2(tex_path, work / tex_path.name)
        command = [str(exe), '-no-shell-escape', '-interaction=nonstopmode', '-halt-on-error', tex_path.name]
        env = dict(os.environ, openin_any='p', openout_any='p')
        with (work / 'console.txt').open('wb') as console:
            try:
                proc = subprocess.Popen(command, cwd=work, stdin=subprocess.DEVNULL,
                    stdout=console, stderr=subprocess.STDOUT, env=env,
                    creationflags=getattr(subprocess, 'CREATE_NO_WINDOW', 0) if os.name == 'nt' else 0)
            except OSError as error:
                return {'ok': False, 'message': str(error)}
            started = time.monotonic()
            why = ''
            while proc.poll() is None:
                if should_stop() or time.monotonic() - started > timeout:
                    why = 'Stopped' if should_stop() else 'Compile timed out'
                    proc.kill()
                    proc.wait()
                    break
                time.sleep(0.1)
        log_path.write_bytes((work / 'console.txt').read_bytes())
        pdf = work / (tex_path.stem + '.pdf')
        if why or proc.returncode or not pdf.is_file() or pdf.stat().st_size == 0:
            return {'ok': False, 'message': why or 'pdfLaTeX failed; inspect the compile log.', 'log': str(log_path)}
        target = dest / pdf.name
        shutil.copy2(pdf, target)
        return {'ok': True, 'pdf': str(target), 'log': str(log_path)}
